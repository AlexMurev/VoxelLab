export interface BlockProperties {
    // --- Графика и Модели ---
    /** Главная текстура блока */
    texture?: string;
	/** Материал блока */
    material?: string;
    /** Индивидуальные текстуры для 6 граней [выш, ниж, сев, юж, вост, зап] */
    "texture-faces"?: string[];
    /** Тип модели блока (например, "block", "xsprite", "custom") */
    model?: string;
    /** Путь/имя 3D модели */
    "model-name"?: string;
    /** Группа отрисовки */
    "draw-group"?: number;
    /** Полупрозрачность блока */
    translucent?: boolean;
    /** Является ли блок полностью непрозрачным/твердым */
    solid?: boolean;
    /** Тип вращения блока игроком */
    rotation?: string;
    /** Конфигурация эффектов частиц */
    particles?: Record<string, unknown>;

    // --- Освещение ---
    /** Свечение блока: массив из 3 чисел [R, G, B] */
    emission?: [number, number, number];
    /** Пропускает ли блок искусственный свет */
    "light-passing"?: boolean;
    /** Пропускает ли блок небесный свет */
    "sky-light-passing"?: boolean;
    /** Отключение теней на блоке */
    shadeless?: boolean;
    /** Мягкое затенение граней (Ambient Occlusion) */
    "ambient-occlusion"?: boolean;
    /** Отсечение невидимых граней соседними блоками */
    culling?: boolean;

    // --- Физика и Коллизии ---
    /** Является ли блок физическим препятствием */
    obstacle?: boolean;
    /** Хитбокс одиночного блока: массив из 6 чисел [x1, y1, z1, x2, y2, z2] */
    hitbox?: [number, number, number, number, number, number];
    /** Сложный составной хитбокс: массив массивов из 6 чисел */
    hitboxes?: Array<[number, number, number, number, number, number]>;
    /** Требуется ли блоку опора под собой */
    grounded?: boolean;

    // --- Взаимодействие ---
    /** Можно ли кликнуть по блоку/выбрать его */
    selectable?: boolean;
    /** Можно ли заменить этот блок другим при клике (как воду или траву) */
    replaceable?: boolean;
    /** Ломается ли блок */
    breakable?: boolean;
    /** Скрыть блок из инвентаря креатива / списков */
    hidden?: boolean;
    /** Предмет, получаемый при клике "выбор блока" */
    "picking-item"?: string;

    // --- Интерфейс и Инвентарь ---
    /** ID макета UI, открываемого при клике */
    "ui-layout"?: string;
    /** Количество слотов внутреннего инвентаря */
    "inventory-size"?: number;
    /** Физический размер мультиблока: массив из 3 целых чисел [x, y, z] */
    size?: [number, number, number];
    /** Поведение блока при разрушении его опоры */
    "grounding-behaviour"?: string;

    // --- Скрипты и Данные ---
    /** Имя привязанного скрипта поведения */
    "script-name"?: string;
    /** Интервал срабатывания таймера (тиков) */
    "tick-interval"?: number;
    /** Теги/категории блока для группировки */
    tags?: string[];

    // --- Свойства пака расширения "base" ---
    /** Прочность блока */
    "base:durability"?: number;

    // --- Системное поле ---
    /** Системное имя/заголовок блока (используется в генераторах) */
    caption?: string;
    /** Ссылка на родительский блок для наследования свойств */
    parent?: string;

    // Индексный сигнатурный тип, чтобы TS не ругался на любые другие кастомные свойства паков
    [key: string]: unknown;
}